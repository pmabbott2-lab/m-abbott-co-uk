CREATE FUNCTION public.request_platform_mfa_recovery(
  p_actor_user_id uuid, p_actor_session_id uuid, p_target_user_id uuid, p_reason text,
  p_cooling_off_minutes integer, p_mode text DEFAULT 'disabled'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v jsonb;
BEGIN
