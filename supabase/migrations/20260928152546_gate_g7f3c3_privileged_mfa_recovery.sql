CREATE FUNCTION public.g7f3c3_fp(p_id uuid)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE WHEN p_id IS NULL THEN NULL
    ELSE left(encode(pg_catalog.sha256(p_id::text::bytea), 'hex'), 12) END;
$$;

