        AND r.status IN ('requested', 'approved', 'executed_awaiting_enrolment')
    );
$$;

-- Usable normal Super Owner: super_owner role, not active break-glass, not locked, verified TOTP.
CREATE FUNCTION public.g7f3c3_usable_normal_so(p_user uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT p_user IS NOT NULL
    AND public.g7f3c3_has_role(p_user, 'super_owner')
    AND NOT public.is_active_break_glass(p_user)
    AND NOT public.is_platform_mfa_recovery_locked(p_user)
    AND public.g7f3c3_has_verified_totp(p_user);
$$;

-- Usable break-glass: super_owner role, active break-glass, not locked, verified TOTP.
CREATE FUNCTION public.g7f3c3_usable_bg(p_user uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT p_user IS NOT NULL
    AND public.g7f3c3_has_role(p_user, 'super_owner')
    AND public.is_active_break_glass(p_user)
    AND NOT public.is_platform_mfa_recovery_locked(p_user)
    AND public.g7f3c3_has_verified_totp(p_user);
$$;

CREATE FUNCTION public.g7f3c3_target_kind(p_user uuid)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT CASE
    WHEN public.g7f3c3_has_role(p_user, 'super_owner') AND public.is_active_break_glass(p_user) THEN 'break_glass'
    WHEN public.g7f3c3_has_role(p_user, 'super_owner') THEN 'normal_so'
    WHEN public.g7f3c3_has_role(p_user, 'super_admin') THEN 'super_admin'
    ELSE NULL
  END;
$$;

-- Final recovery path: after locking p_target there must remain
-- (>=1 usable normal SO AND >=1 usable BG) OR >=2 usable normal SOs; a BG target needs >=2 normal SOs.
CREATE FUNCTION public.g7f3c3_final_path_formula(p_normal_so integer, p_bg integer, p_target_kind text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE
    WHEN p_target_kind = 'break_glass' THEN COALESCE(p_normal_so, 0) >= 2
    ELSE (COALESCE(p_normal_so, 0) >= 1 AND COALESCE(p_bg, 0) >= 1) OR COALESCE(p_normal_so, 0) >= 2
  END;
$$;

CREATE FUNCTION public.g7f3c3_final_path_counts(p_target uuid)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT jsonb_build_object(
    'usable_normal_so', (
      SELECT count(DISTINCT pr.user_id)::integer FROM public.platform_roles pr
      WHERE pr.role::text = 'super_owner' AND pr.user_id <> p_target
        AND public.g7f3c3_usable_normal_so(pr.user_id)),
    'usable_bg', (
      SELECT count(DISTINCT pr.user_id)::integer FROM public.platform_roles pr
      WHERE pr.role::text = 'super_owner' AND pr.user_id <> p_target
        AND public.g7f3c3_usable_bg(pr.user_id))
  );
$$;

CREATE FUNCTION public.g7f3c3_final_path_ok(p_target uuid, p_target_kind text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v jsonb := public.g7f3c3_final_path_counts(p_target);
BEGIN
  RETURN public.g7f3c3_final_path_formula((v->>'usable_normal_so')::integer, (v->>'usable_bg')::integer, p_target_kind);
END;
$$;

-- Server-side fresh-auth re-check from Auth state: session belongs to user, not expired,
-- optional aal2, optional TOTP AMR refreshed within p_fresh_sec. NULL = satisfied, else reason.
CREATE FUNCTION public.g7f3c3_session_check(p_user uuid, p_session uuid, p_require_aal2 boolean, p_fresh_sec integer)
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user uuid;
  v_aal text;
  v_not_after timestamptz;
  v_amr timestamptz;
BEGIN
  IF p_user IS NULL OR p_session IS NULL THEN
    RETURN 'session_missing';
  END IF;
  SELECT s.user_id, s.aal::text, s.not_after INTO v_user, v_aal, v_not_after
  FROM auth.sessions s WHERE s.id = p_session;
  IF NOT FOUND THEN
    RETURN 'session_missing';
  END IF;
  IF v_user <> p_user THEN
    RETURN 'session_user_mismatch';
  END IF;
  IF v_not_after IS NOT NULL AND v_not_after <= pg_catalog.now() THEN
    RETURN 'session_expired';
  END IF;
  IF p_require_aal2 AND v_aal IS DISTINCT FROM 'aal2' THEN
    RETURN 'aal_insufficient';
  END IF;
  IF p_fresh_sec IS NOT NULL THEN
    SELECT max(c.updated_at) INTO v_amr
    FROM auth.mfa_amr_claims c
    WHERE c.session_id = p_session AND c.authentication_method IN ('totp', 'mfa/totp');
    IF v_amr IS NULL THEN
      RETURN 'fresh_mfa_missing';
    END IF;
    IF v_amr < pg_catalog.now() - pg_catalog.make_interval(secs => p_fresh_sec) THEN
      RETURN 'fresh_mfa_stale';
    END IF;
  END IF;
  RETURN NULL;
END;
$$;

CREATE FUNCTION public.g7f3c3_audit(p_event text, p_actor uuid, p_subject uuid, p_meta jsonb)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  INSERT INTO public.security_audit_events (event_type, acting_user_id, subject_user_id, metadata)
  VALUES (
    p_event,
    p_actor,
    p_subject,
    jsonb_build_object('source', 'g7f3c3_mfa_recovery', 'authoritative', true) || COALESCE(p_meta, '{}'::jsonb)
  );
$$;

CREATE FUNCTION public.g7f3c3_deny(
  p_action text, p_reason text, p_actor uuid, p_actor_session uuid,
  p_target uuid, p_request uuid, p_mode text, p_extra jsonb DEFAULT '{}'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  PERFORM public.g7f3c3_audit('MFA_RECOVERY_DENIED', p_actor, p_target,
    jsonb_build_object(
      'action', p_action,
      'result_reason', p_reason,
      'request_id', p_request,
      'actor_session_fp', public.g7f3c3_fp(p_actor_session),
      'mode', public.g7f3c3_mode(p_mode)
    ) || COALESCE(p_extra, '{}'::jsonb));
  RETURN jsonb_build_object('ok', false, 'reason', p_reason, 'request_id', p_request);
END;
$$;

CREATE FUNCTION public.g7f3c3_lock_target(p_target uuid, p_global boolean)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_global THEN
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('g7f3c3:global', 0));
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('g7f3c3:target:' || p_target::text, 0));
END;
$$;

-- Returns the row locked FOR UPDATE after taking the advisory lock(s); NULL row when missing.
CREATE FUNCTION public.g7f3c3_lock_request(p_request uuid, p_global boolean)
RETURNS public.platform_mfa_recovery_requests
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_target uuid;
  r public.platform_mfa_recovery_requests;
BEGIN
  SELECT target_user_id INTO v_target FROM public.platform_mfa_recovery_requests WHERE id = p_request;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  PERFORM public.g7f3c3_lock_target(v_target, p_global);
  SELECT * INTO r FROM public.platform_mfa_recovery_requests WHERE id = p_request FOR UPDATE;
  RETURN r;
END;
$$;

-- Lazily expires an active request whose window has elapsed. An executed request stays locked.
CREATE FUNCTION public.g7f3c3_expire_if_due(p_req public.platform_mfa_recovery_requests, p_mode text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_req.id IS NULL
     OR p_req.status NOT IN ('requested', 'approved', 'executed_awaiting_enrolment')
     OR pg_catalog.now() < p_req.expires_at THEN
    RETURN false;
  END IF;
  UPDATE public.platform_mfa_recovery_requests
  SET status = 'expired',
      terminal_reason = CASE WHEN p_req.executed_at IS NULL THEN 'execution_window_elapsed'
                             ELSE 'enrolment_window_elapsed' END
  WHERE id = p_req.id;
  PERFORM public.g7f3c3_audit('MFA_RECOVERY_EXPIRED', NULL, p_req.target_user_id,
    jsonb_build_object(
      'request_id', p_req.id,
      'target_kind', p_req.target_kind,
      'previous_status', p_req.status,
      'expires_at', p_req.expires_at,
      'target_remains_locked', p_req.executed_at IS NOT NULL,
      'mode', public.g7f3c3_mode(p_mode)
    ));
  RETURN true;
END;
$$;

CREATE FUNCTION public.g7f3c3_authority_snapshot(p_user uuid)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT jsonb_build_object(
    'platform_roles', (SELECT COALESCE(jsonb_agg(pr.id ORDER BY pr.id), '[]'::jsonb) FROM public.platform_roles pr WHERE pr.user_id = p_user),
    'tenant_memberships', (SELECT COALESCE(jsonb_agg(jsonb_build_array(tm.id, tm.role, tm.active) ORDER BY tm.id), '[]'::jsonb)
                           FROM public.tenant_memberships tm WHERE tm.user_id = p_user),
    'super_admin_grants', (SELECT COALESCE(jsonb_agg(jsonb_build_array(g.id, g.access_level, g.revoked_at, g.expires_at) ORDER BY g.id), '[]'::jsonb)
                           FROM public.super_admin_tenant_access g WHERE g.user_id = p_user),
    'support_grants', (SELECT COALESCE(jsonb_agg(jsonb_build_array(g.id, g.revoked_at) ORDER BY g.id), '[]'::jsonb)
                       FROM public.tenant_support_access_grants g WHERE g.grantee_user_id = p_user),
    'emergency_grants', (SELECT COALESCE(jsonb_agg(jsonb_build_array(g.id, g.revoked_at) ORDER BY g.id), '[]'::jsonb)
                         FROM public.tenant_emergency_access_grants g WHERE g.grantee_user_id = p_user)
  );
$$;

-- Removes every MFA factor, refresh token and Auth session of p_target. Not granted to anyone.
CREATE FUNCTION public.g7f3c3_revoke_target_auth(p_target uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_factor_ids jsonb;
  v_factors integer := 0;
  v_refresh integer := 0;
  v_sessions integer := 0;
BEGIN
  SELECT COALESCE(jsonb_agg(f.id ORDER BY f.created_at), '[]'::jsonb) INTO v_factor_ids
  FROM auth.mfa_factors f WHERE f.user_id = p_target;
  DELETE FROM auth.mfa_factors WHERE user_id = p_target;
  GET DIAGNOSTICS v_factors = ROW_COUNT;
  DELETE FROM auth.refresh_tokens WHERE user_id = p_target::text;
  GET DIAGNOSTICS v_refresh = ROW_COUNT;
  DELETE FROM auth.sessions WHERE user_id = p_target;
  GET DIAGNOSTICS v_sessions = ROW_COUNT;
  RETURN jsonb_build_object(
    'removed_factor_ids', v_factor_ids,
    'factors_removed_count', v_factors,
    'refresh_revoked_count', v_refresh,
    'sessions_revoked_count', v_sessions
  );
END;
$$;

CREATE FUNCTION public.g7f3c3_assert_target_revoked(p_target uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM auth.mfa_factors WHERE user_id = p_target) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:factors_remain';
  END IF;
  IF EXISTS (SELECT 1 FROM auth.sessions WHERE user_id = p_target) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:sessions_remain';
  END IF;
  IF EXISTS (SELECT 1 FROM auth.refresh_tokens WHERE user_id = p_target::text) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:refresh_remain';
  END IF;
  IF EXISTS (SELECT 1 FROM public.platform_tenant_access_sessions WHERE platform_user_id = p_target AND ended_at IS NULL) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:g7d_open';
  END IF;
  IF EXISTS (SELECT 1 FROM public.platform_break_glass_sessions WHERE user_id = p_target AND ended_at IS NULL) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:bg_session_open';
  END IF;
  IF NOT public.is_platform_mfa_recovery_locked(p_target) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:lock_missing';
  END IF;
  IF public.is_super_owner(p_target) OR public.is_super_admin(p_target) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:authority_not_suspended';
  END IF;
END;
$$;

-- ---------------------------------------------------------------------------------------------
-- 8. RPC implementations (not granted; wrappers set the write-guard flag)
-- ---------------------------------------------------------------------------------------------
CREATE FUNCTION public.g7f3c3_request_impl(
  p_actor uuid, p_session uuid, p_target uuid, p_reason text, p_cooling_off_minutes integer, p_mode text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_now timestamptz := pg_catalog.now();
  v_reason text := btrim(COALESCE(p_reason, ''));
  v_kind text;
  v_check text;
  v_verified_count integer;
  v_factor uuid;
  v_cool timestamptz;
  v_id uuid;
  v_counts jsonb;
  r public.platform_mfa_recovery_requests;
BEGIN
  IF p_actor IS NULL OR p_target IS NULL THEN
    RAISE EXCEPTION 'invalid_mfa_recovery_args' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  PERFORM public.g7f3c3_lock_target(p_target, false);

  FOR r IN
    SELECT * FROM public.platform_mfa_recovery_requests
    WHERE target_user_id = p_target AND status IN ('requested', 'approved', 'executed_awaiting_enrolment')
    FOR UPDATE
  LOOP
    PERFORM public.g7f3c3_expire_if_due(r, p_mode);
  END LOOP;

  IF p_actor = p_target THEN
    RETURN public.g7f3c3_deny('request', 'self_recovery_denied', p_actor, p_session, p_target, NULL, p_mode);
  END IF;
  v_check := public.g7f3c3_session_check(p_actor, p_session, true, 300);
  IF v_check IS NOT NULL THEN
    RETURN public.g7f3c3_deny('request', v_check, p_actor, p_session, p_target, NULL, p_mode);
  END IF;
  IF NOT public.g7f3c3_usable_normal_so(p_actor) THEN
    RETURN public.g7f3c3_deny('request', 'actor_not_recovery_authority', p_actor, p_session, p_target, NULL, p_mode);
  END IF;
  IF public.g7f3c3_in_recovery(p_actor) THEN
    RETURN public.g7f3c3_deny('request', 'actor_in_recovery', p_actor, p_session, p_target, NULL, p_mode);
  END IF;
  v_kind := public.g7f3c3_target_kind(p_target);
  IF v_kind IS NULL THEN
    RETURN public.g7f3c3_deny('request', 'target_not_privileged', p_actor, p_session, p_target, NULL, p_mode);
  END IF;
  IF length(v_reason) < 10 OR length(v_reason) > 500 THEN
    RETURN public.g7f3c3_deny('request', 'reason_invalid', p_actor, p_session, p_target, NULL, p_mode);
  END IF;
  IF EXISTS (SELECT 1 FROM public.platform_mfa_recovery_requests
             WHERE target_user_id = p_target AND status IN ('requested', 'approved', 'executed_awaiting_enrolment')) THEN
    RETURN public.g7f3c3_deny('request', 'active_request_exists', p_actor, p_session, p_target, NULL, p_mode);
  END IF;

  SELECT count(*)::integer, (array_agg(f.id))[1] INTO v_verified_count, v_factor
  FROM auth.mfa_factors f WHERE f.user_id = p_target AND f.status::text = 'verified';
  IF v_verified_count > 1 THEN
    RETURN public.g7f3c3_deny('request', 'target_factor_ambiguous', p_actor, p_session, p_target, NULL, p_mode);
  END IF;
  IF v_verified_count = 0 AND NOT public.is_platform_mfa_recovery_locked(p_target) THEN
    RETURN public.g7f3c3_deny('request', 'target_has_no_verified_factor', p_actor, p_session, p_target, NULL, p_mode);
  END IF;

  IF v_kind IN ('normal_so', 'break_glass') AND NOT public.g7f3c3_final_path_ok(p_target, v_kind) THEN
    v_counts := public.g7f3c3_final_path_counts(p_target);
    RETURN public.g7f3c3_deny('request', 'final_recovery_path_violation', p_actor, p_session, p_target, NULL, p_mode, v_counts);
  END IF;

  IF v_kind = 'super_admin' THEN
    v_cool := v_now;
  ELSE
    IF p_cooling_off_minutes IS NULL OR p_cooling_off_minutes < 15 OR p_cooling_off_minutes > 10080 THEN
      RETURN public.g7f3c3_deny('request', 'cooling_off_invalid', p_actor, p_session, p_target, NULL, p_mode);
    END IF;
    v_cool := v_now + pg_catalog.make_interval(mins => p_cooling_off_minutes);
  END IF;

  INSERT INTO public.platform_mfa_recovery_requests (
    target_user_id, target_kind, target_factor_id,
    requested_by, requested_session_id, approved_by, approved_session_id, approved_at,
    reason, cooling_off_until, status, created_at, expires_at
  ) VALUES (
    p_target, v_kind, v_factor,
    p_actor, p_session, p_actor, p_session, v_now,
    v_reason, v_cool, 'requested', v_now, v_cool + interval '60 minutes'
  ) RETURNING id INTO v_id;

  PERFORM public.g7f3c3_audit('MFA_RECOVERY_REQUESTED', p_actor, p_target, jsonb_build_object(
    'request_id', v_id,
    'target_kind', v_kind,
    'target_factor_id', v_factor,
    'reason', v_reason,
    'cooling_off_until', v_cool,
    'expires_at', v_cool + interval '60 minutes',
    'requires_second_approval', v_kind = 'break_glass',
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  ));
  PERFORM public.g7f3c3_audit('MFA_RECOVERY_APPROVED', p_actor, p_target, jsonb_build_object(
    'request_id', v_id,
    'target_kind', v_kind,
    'approval_index', 1,
    'approval_basis', 'initiator_normal_super_owner',
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  ));

  RETURN jsonb_build_object(
    'ok', true,
    'request_id', v_id,
    'target_kind', v_kind,
    'status', 'requested',
    'cooling_off_until', v_cool,
    'expires_at', v_cool + interval '60 minutes',
    'requires_second_approval', v_kind = 'break_glass'
  );
END;
$$;

CREATE FUNCTION public.g7f3c3_approve_impl(p_actor uuid, p_session uuid, p_request uuid, p_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  r public.platform_mfa_recovery_requests;
  v_check text;
  v_basis text;
BEGIN
  IF p_actor IS NULL OR p_request IS NULL THEN
    RAISE EXCEPTION 'invalid_mfa_recovery_args' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  r := public.g7f3c3_lock_request(p_request, false);
  IF r.id IS NULL THEN
    RETURN public.g7f3c3_deny('approve', 'request_not_found', p_actor, p_session, NULL, p_request, p_mode);
  END IF;
  IF public.g7f3c3_expire_if_due(r, p_mode) THEN
    RETURN public.g7f3c3_deny('approve', 'request_expired', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF r.status <> 'requested' THEN
    RETURN public.g7f3c3_deny('approve', 'request_not_pending', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('status', r.status));
  END IF;
  IF r.target_kind = 'super_admin' THEN
    RETURN public.g7f3c3_deny('approve', 'second_approval_not_applicable', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF p_actor = r.target_user_id THEN
    RETURN public.g7f3c3_deny('approve', 'self_approval_denied', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF p_actor = r.requested_by OR p_actor = r.approved_by THEN
    RETURN public.g7f3c3_deny('approve', 'approver_not_distinct', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  v_check := public.g7f3c3_session_check(p_actor, p_session, true, 300);
  IF v_check IS NOT NULL THEN
    RETURN public.g7f3c3_deny('approve', v_check, p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF p_session = r.approved_session_id THEN
    RETURN public.g7f3c3_deny('approve', 'approval_session_not_distinct', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF public.g7f3c3_usable_normal_so(p_actor) THEN
    v_basis := 'normal_super_owner';
  ELSIF r.target_kind = 'normal_so' AND public.g7f3c3_usable_bg(p_actor) THEN
    v_basis := 'break_glass';
  ELSE
    RETURN public.g7f3c3_deny('approve', 'actor_not_recovery_authority', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF public.g7f3c3_in_recovery(p_actor) THEN
    RETURN public.g7f3c3_deny('approve', 'actor_in_recovery', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;

  UPDATE public.platform_mfa_recovery_requests
  SET second_approved_by = p_actor,
      second_session_id = p_session,
      second_approved_at = pg_catalog.now(),
      status = 'approved'
  WHERE id = r.id;

  PERFORM public.g7f3c3_audit('MFA_RECOVERY_SECOND_APPROVAL', p_actor, r.target_user_id, jsonb_build_object(
    'request_id', r.id,
    'target_kind', r.target_kind,
    'approval_index', 2,
    'approval_basis', v_basis,
    'expedites_cooling_off', r.target_kind = 'normal_so',
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  ));

  RETURN jsonb_build_object('ok', true, 'request_id', r.id, 'status', 'approved', 'approval_basis', v_basis);
END;
$$;

CREATE FUNCTION public.g7f3c3_execute_impl(p_actor uuid, p_session uuid, p_request uuid, p_grant_hash text, p_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  r public.platform_mfa_recovery_requests;
  v_now timestamptz := pg_catalog.now();
  v_check text;
  v_second_ok boolean;
  v_verified uuid[];
  v_before jsonb;
  v_after jsonb;
  v_revoked jsonb;
  v_g7d integer := 0;
  v_bg integer := 0;
  v_bg_row public.platform_break_glass_sessions;
  v_counts jsonb;
  v_meta jsonb;
BEGIN
  IF p_actor IS NULL OR p_request IS NULL THEN
    RAISE EXCEPTION 'invalid_mfa_recovery_args' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  r := public.g7f3c3_lock_request(p_request, true);
  IF r.id IS NULL THEN
    RETURN public.g7f3c3_deny('execute', 'request_not_found', p_actor, p_session, NULL, p_request, p_mode);
  END IF;
  IF public.g7f3c3_expire_if_due(r, p_mode) THEN
    RETURN public.g7f3c3_deny('execute', 'request_expired', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF r.status NOT IN ('requested', 'approved') THEN
    RETURN public.g7f3c3_deny('execute', 'request_not_executable', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('status', r.status));
  END IF;
  IF r.target_kind = 'break_glass' AND r.status <> 'approved' THEN
    RETURN public.g7f3c3_deny('execute', 'second_approval_required', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF (r.target_kind = 'break_glass' OR (r.target_kind = 'normal_so' AND r.status = 'requested'))
     AND v_now < r.cooling_off_until THEN
    RETURN public.g7f3c3_deny('execute', 'cooling_off_active', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('cooling_off_until', r.cooling_off_until));
  END IF;

  IF p_actor = r.target_user_id THEN
    RETURN public.g7f3c3_deny('execute', 'self_recovery_denied', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF p_actor IS DISTINCT FROM r.requested_by AND p_actor IS DISTINCT FROM r.second_approved_by THEN
    RETURN public.g7f3c3_deny('execute', 'executor_not_request_authority', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  v_check := public.g7f3c3_session_check(p_actor, p_session, true, 300);
  IF v_check IS NOT NULL THEN
    RETURN public.g7f3c3_deny('execute', v_check, p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF NOT public.g7f3c3_usable_normal_so(p_actor) THEN
    RETURN public.g7f3c3_deny('execute', 'actor_not_recovery_authority', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF public.g7f3c3_in_recovery(p_actor) THEN
    RETURN public.g7f3c3_deny('execute', 'actor_in_recovery', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;

  -- Approvers must still hold their authority now.
  IF NOT public.g7f3c3_usable_normal_so(r.approved_by) OR public.g7f3c3_in_recovery(r.approved_by) THEN
    UPDATE public.platform_mfa_recovery_requests SET status = 'denied', terminal_reason = 'approver_no_longer_qualified'
    WHERE id = r.id;
    RETURN public.g7f3c3_deny('execute', 'approver_no_longer_qualified', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('approval_index', 1, 'request_terminal', true));
  END IF;
  IF r.second_approved_by IS NOT NULL THEN
    v_second_ok := (public.g7f3c3_usable_normal_so(r.second_approved_by)
                    OR (r.target_kind = 'normal_so' AND public.g7f3c3_usable_bg(r.second_approved_by)))
                   AND NOT public.g7f3c3_in_recovery(r.second_approved_by);
    IF NOT v_second_ok THEN
      UPDATE public.platform_mfa_recovery_requests SET status = 'denied', terminal_reason = 'approver_no_longer_qualified'
      WHERE id = r.id;
      RETURN public.g7f3c3_deny('execute', 'approver_no_longer_qualified', p_actor, p_session, r.target_user_id, r.id, p_mode,
        jsonb_build_object('approval_index', 2, 'request_terminal', true));
    END IF;
  END IF;

  IF public.g7f3c3_target_kind(r.target_user_id) IS DISTINCT FROM r.target_kind THEN
    UPDATE public.platform_mfa_recovery_requests SET status = 'denied', terminal_reason = 'target_kind_changed'
    WHERE id = r.id;
    RETURN public.g7f3c3_deny('execute', 'target_kind_changed', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('request_terminal', true));
  END IF;

  IF r.target_kind IN ('normal_so', 'break_glass') AND NOT public.g7f3c3_final_path_ok(r.target_user_id, r.target_kind) THEN
    v_counts := public.g7f3c3_final_path_counts(r.target_user_id);
    RETURN public.g7f3c3_deny('execute', 'final_recovery_path_violation', p_actor, p_session, r.target_user_id, r.id, p_mode, v_counts);
  END IF;

  SELECT COALESCE(array_agg(f.id), '{}') INTO v_verified
  FROM auth.mfa_factors f WHERE f.user_id = r.target_user_id AND f.status::text = 'verified';
  IF (r.target_factor_id IS NOT NULL AND v_verified IS DISTINCT FROM ARRAY[r.target_factor_id])
     OR (r.target_factor_id IS NULL AND cardinality(v_verified) <> 0) THEN
    UPDATE public.platform_mfa_recovery_requests SET status = 'denied', terminal_reason = 'target_factor_changed'
    WHERE id = r.id;
    RETURN public.g7f3c3_deny('execute', 'target_factor_changed', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('bound_factor_id', r.target_factor_id, 'verified_factor_count', cardinality(v_verified), 'request_terminal', true));
  END IF;

  IF p_grant_hash IS NULL OR p_grant_hash !~ '^[0-9a-f]{64}$' THEN
    RETURN public.g7f3c3_deny('execute', 'grant_hash_invalid', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;

  -- Destructive section: everything below commits or rolls back together.
  v_before := public.g7f3c3_authority_snapshot(r.target_user_id);
  v_revoked := public.g7f3c3_revoke_target_auth(r.target_user_id);

  UPDATE public.platform_tenant_access_sessions
  SET ended_at = v_now
  WHERE platform_user_id = r.target_user_id AND ended_at IS NULL;
  GET DIAGNOSTICS v_g7d = ROW_COUNT;

  FOR v_bg_row IN
    SELECT * FROM public.platform_break_glass_sessions
    WHERE user_id = r.target_user_id AND ended_at IS NULL
    FOR UPDATE
  LOOP
    PERFORM public._end_break_glass_platform_session_row(v_bg_row, 'mfa_recovery', v_now);
    v_bg := v_bg + 1;
  END LOOP;

  INSERT INTO public.platform_mfa_recovery_locks (user_id, request_id, locked_at)
  VALUES (r.target_user_id, r.id, v_now)
  ON CONFLICT (user_id) DO UPDATE SET request_id = EXCLUDED.request_id, locked_at = EXCLUDED.locked_at;

  UPDATE public.platform_mfa_recovery_requests
  SET status = 'executed_awaiting_enrolment',
      executed_at = v_now,
      executed_by = p_actor,
      executed_session_id = p_session,
      expires_at = v_now + interval '24 hours',
      grant_hash = p_grant_hash,
      grant_issued_at = v_now,
      grant_expires_at = v_now + interval '30 minutes',
      grant_redeemed_at = NULL,
      redeemed_session_id = NULL,
      grant_failed_attempts = 0
  WHERE id = r.id;

  v_meta := jsonb_build_object(
    'request_id', r.id,
    'target_kind', r.target_kind,
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  );
  PERFORM public.g7f3c3_audit('MFA_RECOVERY_EXECUTED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
    'expedited', r.status = 'approved' AND r.target_kind = 'normal_so',
    'second_approved_by', r.second_approved_by,
    'recovery_expires_at', v_now + interval '24 hours'
  ));
  PERFORM public.g7f3c3_audit('MFA_FACTOR_REMOVED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
    'removed_factor_ids', v_revoked->'removed_factor_ids',
    'factors_removed_count', v_revoked->'factors_removed_count',
    'bound_factor_id', r.target_factor_id,
    'reason_code', 'mfa_recovery'
  ));
  PERFORM public.g7f3c3_audit('MFA_TARGET_SESSIONS_REVOKED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
    'sessions_revoked_count', v_revoked->'sessions_revoked_count',
    'refresh_revoked_count', v_revoked->'refresh_revoked_count',
    'reason_code', 'mfa_recovery'
  ));
  IF v_g7d > 0 THEN
    PERFORM public.g7f3c3_audit('PLATFORM_TENANT_ENTRY_ENDED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
      'g7d_ended_count', v_g7d, 'end_reason', 'mfa_recovery'));
  END IF;
  IF v_bg > 0 THEN
    PERFORM public.g7f3c3_audit('BREAK_GLASS_SESSION_ENDED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
      'bg_sessions_ended_count', v_bg, 'end_reason', 'mfa_recovery'));
  END IF;
  PERFORM public.g7f3c3_audit('MFA_RECOVERY_GRANT_ISSUED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
    'grant_expires_at', v_now + interval '30 minutes',
    'reissue', false
  ));

  PERFORM public.g7f3c3_assert_target_revoked(r.target_user_id);
  v_after := public.g7f3c3_authority_snapshot(r.target_user_id);
  IF v_after IS DISTINCT FROM v_before THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:authority_records_changed';
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'request_id', r.id,
    'status', 'executed_awaiting_enrolment',
    'target_user_id', r.target_user_id,
    'grant_expires_at', v_now + interval '30 minutes',
    'recovery_expires_at', v_now + interval '24 hours',
    'factors_removed_count', v_revoked->'factors_removed_count',
    'sessions_revoked_count', v_revoked->'sessions_revoked_count',
    'refresh_revoked_count', v_revoked->'refresh_revoked_count',
    'g7d_ended_count', v_g7d,
    'bg_sessions_ended_count', v_bg
  );
END;
$$;

CREATE FUNCTION public.g7f3c3_reissue_impl(p_actor uuid, p_session uuid, p_request uuid, p_grant_hash text, p_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  r public.platform_mfa_recovery_requests;
  v_now timestamptz := pg_catalog.now();
  v_check text;
  v_before jsonb;
  v_revoked jsonb;
  v_meta jsonb;
BEGIN
  IF p_actor IS NULL OR p_request IS NULL THEN
    RAISE EXCEPTION 'invalid_mfa_recovery_args' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  r := public.g7f3c3_lock_request(p_request, false);
  IF r.id IS NULL THEN
    RETURN public.g7f3c3_deny('reissue', 'request_not_found', p_actor, p_session, NULL, p_request, p_mode);
  END IF;
  IF public.g7f3c3_expire_if_due(r, p_mode) THEN
    RETURN public.g7f3c3_deny('reissue', 'request_expired', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF r.status <> 'executed_awaiting_enrolment' THEN
    RETURN public.g7f3c3_deny('reissue', 'recovery_not_awaiting_enrolment', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('status', r.status));
  END IF;
  IF p_actor = r.target_user_id THEN
    RETURN public.g7f3c3_deny('reissue', 'self_recovery_denied', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF p_actor IS DISTINCT FROM r.requested_by AND p_actor IS DISTINCT FROM r.executed_by
     AND p_actor IS DISTINCT FROM r.second_approved_by THEN
    RETURN public.g7f3c3_deny('reissue', 'executor_not_request_authority', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  v_check := public.g7f3c3_session_check(p_actor, p_session, true, 300);
  IF v_check IS NOT NULL THEN
    RETURN public.g7f3c3_deny('reissue', v_check, p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF NOT public.g7f3c3_usable_normal_so(p_actor) OR public.g7f3c3_in_recovery(p_actor) THEN
    RETURN public.g7f3c3_deny('reissue', 'actor_not_recovery_authority', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF p_grant_hash IS NULL OR p_grant_hash !~ '^[0-9a-f]{64}$' THEN
    RETURN public.g7f3c3_deny('reissue', 'grant_hash_invalid', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;

  v_before := public.g7f3c3_authority_snapshot(r.target_user_id);
  -- Anything enrolled or signed in since execution is discarded with the old grant.
  v_revoked := public.g7f3c3_revoke_target_auth(r.target_user_id);

  UPDATE public.platform_mfa_recovery_requests
  SET grant_hash = p_grant_hash,
      grant_issued_at = v_now,
      grant_expires_at = v_now + interval '30 minutes',
      grant_redeemed_at = NULL,
      redeemed_session_id = NULL,
      grant_failed_attempts = 0
  WHERE id = r.id;

  v_meta := jsonb_build_object(
    'request_id', r.id,
    'target_kind', r.target_kind,
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  );
  IF (v_revoked->>'factors_removed_count')::integer > 0 THEN
    PERFORM public.g7f3c3_audit('MFA_FACTOR_REMOVED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
      'removed_factor_ids', v_revoked->'removed_factor_ids',
      'factors_removed_count', v_revoked->'factors_removed_count',
      'reason_code', 'mfa_recovery_grant_reissue'));
  END IF;
  PERFORM public.g7f3c3_audit('MFA_TARGET_SESSIONS_REVOKED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
    'sessions_revoked_count', v_revoked->'sessions_revoked_count',
    'refresh_revoked_count', v_revoked->'refresh_revoked_count',
    'reason_code', 'mfa_recovery_grant_reissue'));
  PERFORM public.g7f3c3_audit('MFA_RECOVERY_GRANT_ISSUED', p_actor, r.target_user_id, v_meta || jsonb_build_object(
    'grant_expires_at', v_now + interval '30 minutes',
    'reissue', true));

  PERFORM public.g7f3c3_assert_target_revoked(r.target_user_id);
  IF public.g7f3c3_authority_snapshot(r.target_user_id) IS DISTINCT FROM v_before THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:authority_records_changed';
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'request_id', r.id,
    'status', 'executed_awaiting_enrolment',
    'target_user_id', r.target_user_id,
    'grant_expires_at', v_now + interval '30 minutes',
    'recovery_expires_at', r.expires_at
  );
END;
$$;

CREATE FUNCTION public.g7f3c3_redeem_impl(p_user uuid, p_session uuid, p_grant_hash text, p_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_request uuid;
  r public.platform_mfa_recovery_requests;
  v_check text;
  v_session_created timestamptz;
  v_attempts integer;
BEGIN
  IF p_user IS NULL THEN
    RAISE EXCEPTION 'invalid_mfa_recovery_args' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  SELECT l.request_id INTO v_request FROM public.platform_mfa_recovery_locks l WHERE l.user_id = p_user;
  IF NOT FOUND THEN
    RETURN public.g7f3c3_deny('redeem', 'no_recovery_in_progress', p_user, p_session, p_user, NULL, p_mode);
  END IF;
  r := public.g7f3c3_lock_request(v_request, false);
  IF r.id IS NULL OR r.target_user_id <> p_user THEN
    RETURN public.g7f3c3_deny('redeem', 'no_recovery_in_progress', p_user, p_session, p_user, v_request, p_mode);
  END IF;
  IF public.g7f3c3_expire_if_due(r, p_mode) THEN
    RETURN public.g7f3c3_deny('redeem', 'request_expired', p_user, p_session, p_user, r.id, p_mode);
  END IF;
  IF r.status <> 'executed_awaiting_enrolment' THEN
    RETURN public.g7f3c3_deny('redeem', 'recovery_not_awaiting_enrolment', p_user, p_session, p_user, r.id, p_mode,
      jsonb_build_object('status', r.status));
  END IF;
  IF r.grant_redeemed_at IS NOT NULL THEN
    RETURN public.g7f3c3_deny('redeem', 'grant_already_redeemed', p_user, p_session, p_user, r.id, p_mode);
  END IF;
  IF r.grant_expires_at <= pg_catalog.now() THEN
    RETURN public.g7f3c3_deny('redeem', 'grant_expired', p_user, p_session, p_user, r.id, p_mode);
  END IF;
  IF p_grant_hash IS NULL OR p_grant_hash !~ '^[0-9a-f]{64}$' OR p_grant_hash <> r.grant_hash THEN
    v_attempts := r.grant_failed_attempts + 1;
    UPDATE public.platform_mfa_recovery_requests
    SET grant_failed_attempts = v_attempts,
        grant_expires_at = CASE WHEN v_attempts >= 5 THEN LEAST(grant_expires_at, pg_catalog.now()) ELSE grant_expires_at END
    WHERE id = r.id;
    RETURN public.g7f3c3_deny('redeem', 'grant_mismatch', p_user, p_session, p_user, r.id, p_mode,
      jsonb_build_object('failed_attempts', v_attempts, 'grant_invalidated', v_attempts >= 5));
  END IF;
  v_check := public.g7f3c3_session_check(p_user, p_session, false, NULL);
  IF v_check IS NOT NULL THEN
    RETURN public.g7f3c3_deny('redeem', v_check, p_user, p_session, p_user, r.id, p_mode);
  END IF;
  SELECT s.created_at INTO v_session_created FROM auth.sessions s WHERE s.id = p_session;
  IF v_session_created IS NULL OR v_session_created <= r.grant_issued_at THEN
    RETURN public.g7f3c3_deny('redeem', 'session_predates_recovery', p_user, p_session, p_user, r.id, p_mode);
  END IF;

  UPDATE public.platform_mfa_recovery_requests
  SET grant_redeemed_at = pg_catalog.now(),
      redeemed_session_id = p_session
  WHERE id = r.id;

  PERFORM public.g7f3c3_audit('MFA_RECOVERY_GRANT_REDEEMED', p_user, p_user, jsonb_build_object(
    'request_id', r.id,
    'target_kind', r.target_kind,
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  ));

  RETURN jsonb_build_object('ok', true, 'request_id', r.id, 'status', r.status, 'recovery_expires_at', r.expires_at);
END;
$$;

CREATE FUNCTION public.g7f3c3_complete_impl(p_user uuid, p_session uuid, p_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_request uuid;
  r public.platform_mfa_recovery_requests;
  v_check text;
  v_session_factor uuid;
  v_verified_count integer;
  v_factor uuid;
  v_factor_type text;
  v_factor_created timestamptz;
  v_factor_ids jsonb;
  v_before jsonb;
BEGIN
  IF p_user IS NULL THEN
    RAISE EXCEPTION 'invalid_mfa_recovery_args' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  SELECT l.request_id INTO v_request FROM public.platform_mfa_recovery_locks l WHERE l.user_id = p_user;
  IF NOT FOUND THEN
    RETURN public.g7f3c3_deny('complete', 'no_recovery_in_progress', p_user, p_session, p_user, NULL, p_mode);
  END IF;
  r := public.g7f3c3_lock_request(v_request, false);
  IF r.id IS NULL OR r.target_user_id <> p_user THEN
    RETURN public.g7f3c3_deny('complete', 'no_recovery_in_progress', p_user, p_session, p_user, v_request, p_mode);
  END IF;
  IF public.g7f3c3_expire_if_due(r, p_mode) THEN
    RETURN public.g7f3c3_deny('complete', 'request_expired', p_user, p_session, p_user, r.id, p_mode);
  END IF;
  IF r.status <> 'executed_awaiting_enrolment' THEN
    RETURN public.g7f3c3_deny('complete', 'recovery_not_awaiting_enrolment', p_user, p_session, p_user, r.id, p_mode,
      jsonb_build_object('status', r.status));
  END IF;
  IF r.grant_redeemed_at IS NULL THEN
    RETURN public.g7f3c3_deny('complete', 'grant_not_redeemed', p_user, p_session, p_user, r.id, p_mode);
  END IF;
  IF p_session IS NULL OR p_session IS DISTINCT FROM r.redeemed_session_id THEN
    RETURN public.g7f3c3_deny('complete', 'session_not_redeemed_session', p_user, p_session, p_user, r.id, p_mode);
  END IF;
  v_check := public.g7f3c3_session_check(p_user, p_session, true, 300);
  IF v_check IS NOT NULL THEN
    RETURN public.g7f3c3_deny('complete', v_check, p_user, p_session, p_user, r.id, p_mode);
  END IF;

  SELECT s.factor_id INTO v_session_factor FROM auth.sessions s WHERE s.id = p_session;
  SELECT count(*)::integer, COALESCE(jsonb_agg(f.id), '[]'::jsonb) INTO v_verified_count, v_factor_ids
  FROM auth.mfa_factors f WHERE f.user_id = p_user AND f.status::text = 'verified';
  IF v_verified_count = 1 THEN
    SELECT f.id, f.factor_type::text, f.created_at INTO v_factor, v_factor_type, v_factor_created
    FROM auth.mfa_factors f WHERE f.user_id = p_user AND f.status::text = 'verified';
  END IF;

  IF v_verified_count <> 1
     OR v_factor_type IS DISTINCT FROM 'totp'
     OR v_factor_created <= r.grant_redeemed_at
     OR v_session_factor IS DISTINCT FROM v_factor THEN
    -- Fail closed: unexpected factor state (e.g. a factor enrolled outside the redeemed flow).
    UPDATE public.platform_mfa_recovery_requests
    SET status = 'failed', terminal_reason = 'unexpected_factor_state'
    WHERE id = r.id;
    RETURN public.g7f3c3_deny('complete', 'unexpected_factor_state', p_user, p_session, p_user, r.id, p_mode,
      jsonb_build_object(
        'verified_factor_count', v_verified_count,
        'verified_factor_ids', v_factor_ids,
        'session_factor_id', v_session_factor,
        'factor_created_before_redemption', v_factor_created IS NOT NULL AND v_factor_created <= r.grant_redeemed_at,
        'flagged', true,
        'request_terminal', true,
        'target_remains_locked', true));
  END IF;

  v_before := public.g7f3c3_authority_snapshot(p_user);

  UPDATE public.platform_mfa_recovery_requests
  SET status = 'completed',
      completed_at = pg_catalog.now(),
      replacement_factor_id = v_factor
  WHERE id = r.id;

  DELETE FROM public.platform_mfa_recovery_locks WHERE user_id = p_user AND request_id = r.id;

  PERFORM public.g7f3c3_audit('MFA_REPLACEMENT_ENROLLED', p_user, p_user, jsonb_build_object(
    'request_id', r.id,
    'target_kind', r.target_kind,
    'replacement_factor_id', v_factor,
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  ));
  PERFORM public.g7f3c3_audit('MFA_RECOVERY_COMPLETED', p_user, p_user, jsonb_build_object(
    'request_id', r.id,
    'target_kind', r.target_kind,
    'replacement_factor_id', v_factor,
    'executed_at', r.executed_at,
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  ));

  IF public.is_platform_mfa_recovery_locked(p_user) THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:lock_remains';
  END IF;
  IF public.g7f3c3_authority_snapshot(p_user) IS DISTINCT FROM v_before THEN
    RAISE EXCEPTION 'g7f3c3_postcondition_failed:authority_records_changed';
  END IF;

  RETURN jsonb_build_object('ok', true, 'request_id', r.id, 'status', 'completed', 'replacement_factor_id', v_factor);
END;
$$;

CREATE FUNCTION public.g7f3c3_cancel_impl(p_actor uuid, p_session uuid, p_request uuid, p_reason text, p_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  r public.platform_mfa_recovery_requests;
  v_check text;
  v_basis text;
  v_reason text := NULLIF(btrim(COALESCE(p_reason, '')), '');
BEGIN
  IF p_actor IS NULL OR p_request IS NULL THEN
    RAISE EXCEPTION 'invalid_mfa_recovery_args' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  r := public.g7f3c3_lock_request(p_request, false);
  IF r.id IS NULL THEN
    RETURN public.g7f3c3_deny('cancel', 'request_not_found', p_actor, p_session, NULL, p_request, p_mode);
  END IF;
  IF public.g7f3c3_expire_if_due(r, p_mode) THEN
    RETURN public.g7f3c3_deny('cancel', 'request_expired', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF r.status = 'executed_awaiting_enrolment' THEN
    RETURN public.g7f3c3_deny('cancel', 'cannot_cancel_after_execution', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF r.status NOT IN ('requested', 'approved') THEN
    RETURN public.g7f3c3_deny('cancel', 'request_terminal', p_actor, p_session, r.target_user_id, r.id, p_mode,
      jsonb_build_object('status', r.status));
  END IF;
  v_check := public.g7f3c3_session_check(p_actor, p_session, true, 300);
  IF v_check IS NOT NULL THEN
    RETURN public.g7f3c3_deny('cancel', v_check, p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF p_actor = r.target_user_id THEN
    IF public.is_platform_mfa_recovery_locked(p_actor) OR NOT public.g7f3c3_has_verified_totp(p_actor) THEN
      RETURN public.g7f3c3_deny('cancel', 'actor_cannot_cancel', p_actor, p_session, r.target_user_id, r.id, p_mode);
    END IF;
    v_basis := 'target';
  ELSIF public.g7f3c3_usable_normal_so(p_actor) THEN
    v_basis := 'normal_super_owner';
  ELSIF public.g7f3c3_usable_bg(p_actor) THEN
    v_basis := 'break_glass';
  ELSE
    RETURN public.g7f3c3_deny('cancel', 'actor_cannot_cancel', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;
  IF v_reason IS NOT NULL AND length(v_reason) > 500 THEN
    RETURN public.g7f3c3_deny('cancel', 'reason_invalid', p_actor, p_session, r.target_user_id, r.id, p_mode);
  END IF;

  UPDATE public.platform_mfa_recovery_requests
  SET status = 'cancelled',
      cancelled_at = pg_catalog.now(),
      cancelled_by = p_actor,
      terminal_reason = 'cancelled_by_' || v_basis
  WHERE id = r.id;

  PERFORM public.g7f3c3_audit('MFA_RECOVERY_CANCELLED', p_actor, r.target_user_id, jsonb_build_object(
    'request_id', r.id,
    'target_kind', r.target_kind,
    'previous_status', r.status,
    'cancel_basis', v_basis,
    'reason', v_reason,
    'actor_session_fp', public.g7f3c3_fp(p_session),
    'mode', public.g7f3c3_mode(p_mode)
  ));

  RETURN jsonb_build_object('ok', true, 'request_id', r.id, 'status', 'cancelled', 'cancel_basis', v_basis);
END;
$$;

CREATE FUNCTION public.g7f3c3_expire_sweep_impl(p_mode text)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_id uuid;
  r public.platform_mfa_recovery_requests;
  v_count integer := 0;
BEGIN
  FOR v_id IN
    SELECT id FROM public.platform_mfa_recovery_requests
    WHERE status IN ('requested', 'approved', 'executed_awaiting_enrolment') AND expires_at <= pg_catalog.now()
  LOOP
    r := public.g7f3c3_lock_request(v_id, false);
    IF public.g7f3c3_expire_if_due(r, p_mode) THEN
      v_count := v_count + 1;
    END IF;
  END LOOP;
  RETURN v_count;
END;
$$;

