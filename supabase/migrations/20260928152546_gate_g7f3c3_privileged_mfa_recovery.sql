-- Own recovery state (target-facing). Never returns grant_hash or another user's data.
CREATE FUNCTION public.get_platform_mfa_recovery_self_state(p_user_id uuid, p_session_id uuid DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_lock public.platform_mfa_recovery_locks;
  r public.platform_mfa_recovery_requests;
  v_pending jsonb;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN jsonb_build_object('locked', false);
  END IF;
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
           'request_id', q.id, 'status', q.status, 'target_kind', q.target_kind,
           'cooling_off_until', q.cooling_off_until, 'expires_at', q.expires_at,
           'created_at', q.created_at) ORDER BY q.created_at DESC), '[]'::jsonb)
    INTO v_pending
  FROM public.platform_mfa_recovery_requests q
  WHERE q.target_user_id = p_user_id AND q.status IN ('requested', 'approved');

  SELECT * INTO v_lock FROM public.platform_mfa_recovery_locks WHERE user_id = p_user_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('locked', false, 'pending_requests', v_pending);
  END IF;
  SELECT * INTO r FROM public.platform_mfa_recovery_requests WHERE id = v_lock.request_id;
  RETURN jsonb_build_object(
    'locked', true,
    'request_id', r.id,
    'status', CASE WHEN r.status = 'executed_awaiting_enrolment' AND pg_catalog.now() >= r.expires_at
                   THEN 'expired' ELSE r.status END,
    'target_kind', r.target_kind,
    'executed_at', r.executed_at,
    'recovery_expires_at', r.expires_at,
    'grant_expires_at', r.grant_expires_at,
    'grant_usable', r.status = 'executed_awaiting_enrolment' AND r.grant_redeemed_at IS NULL
                    AND r.grant_expires_at > pg_catalog.now() AND r.expires_at > pg_catalog.now(),
    'grant_redeemed', r.grant_redeemed_at IS NOT NULL,
    'grant_redeemed_at', r.grant_redeemed_at,
    'redeemed_by_this_session', p_session_id IS NOT NULL AND r.redeemed_session_id = p_session_id,
    'pending_requests', v_pending
  );
END;
$$;

