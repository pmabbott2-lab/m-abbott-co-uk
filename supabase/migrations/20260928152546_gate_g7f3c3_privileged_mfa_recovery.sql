-- G7F-3C3: privileged MFA recovery and factor replacement (Option D).
--
-- Recovery suspends platform authority; it never removes platform_roles, tenant_memberships or
-- grants. While public.platform_mfa_recovery_locks holds a row for a user, is_super_owner() and
-- is_super_admin() return false for that user, so every RLS policy, SECURITY DEFINER helper and
-- server authority check that derives from them denies — independent of PRIVILEGED_MFA_MODE and of
-- any access token issued before the recovery.
--
-- All state changes go through service_role-only SECURITY DEFINER RPCs that lock the request row
-- (SELECT ... FOR UPDATE) plus a per-target advisory lock (execution also takes a global lock) and
-- re-check every authority and invariant inside the lock. The tables are write-guarded so even a
-- service_role session cannot mutate them directly.
--
-- Auth schema assumptions (verified on staging before this migration, pinned by
-- scripts/g7f3c3-mfa-recovery-verify.sql):
--   auth.mfa_challenges.factor_id -> auth.mfa_factors ON DELETE CASCADE
--   auth.mfa_recovery_code_sets.mfa_factor_id -> auth.mfa_factors ON DELETE CASCADE
--   auth.refresh_tokens.session_id / auth.mfa_amr_claims.session_id -> auth.sessions ON DELETE CASCADE
--   auth.refresh_tokens.user_id is varchar; auth.sessions has aal, factor_id, not_after, created_at.
--
-- The one-time recovery grant is generated by the application server; only its SHA-256 hex digest
-- reaches the database, and that digest is not readable through any grant.

-- ---------------------------------------------------------------------------------------------
-- 1. Break-glass session end reason: add mfa_recovery (D1 time/idle/binding invariants unchanged)
-- ---------------------------------------------------------------------------------------------
ALTER TABLE public.platform_break_glass_sessions
  DROP CONSTRAINT IF EXISTS platform_break_glass_sessions_end_reason_chk;
ALTER TABLE public.platform_break_glass_sessions
  ADD CONSTRAINT platform_break_glass_sessions_end_reason_chk CHECK (
    end_reason IS NULL OR end_reason = ANY (ARRAY[
      'logout'::text, 'absolute_expired'::text, 'idle_expired'::text,
      'classification_removed'::text, 'role_removed'::text, 'replaced'::text,
      'mfa_recovery'::text
    ])
  );

-- ---------------------------------------------------------------------------------------------
-- 2. Recovery requests
-- ---------------------------------------------------------------------------------------------
CREATE TABLE public.platform_mfa_recovery_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  target_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  target_kind text NOT NULL,
  target_factor_id uuid,
  requested_by uuid NOT NULL,
  requested_session_id uuid NOT NULL,
  approved_by uuid NOT NULL,
  approved_session_id uuid NOT NULL,
  approved_at timestamptz NOT NULL,
  second_approved_by uuid,
  second_session_id uuid,
  second_approved_at timestamptz,
  executed_by uuid,
  executed_session_id uuid,
  cancelled_by uuid,
  reason text NOT NULL,
  terminal_reason text,
  cooling_off_until timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'requested',
  created_at timestamptz NOT NULL DEFAULT now(),
  executed_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  expires_at timestamptz NOT NULL,
  grant_hash text,
  grant_issued_at timestamptz,
  grant_expires_at timestamptz,
  grant_redeemed_at timestamptz,
  grant_failed_attempts integer NOT NULL DEFAULT 0,
  redeemed_session_id uuid,
  replacement_factor_id uuid,
  evidence_type text,
  evidence_ref text,
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT platform_mfa_recovery_target_kind_chk
    CHECK (target_kind IN ('normal_so', 'super_admin', 'break_glass')),
  CONSTRAINT platform_mfa_recovery_status_chk
    CHECK (status IN ('requested', 'approved', 'executed_awaiting_enrolment', 'completed',
                      'cancelled', 'expired', 'denied', 'failed')),
  CONSTRAINT platform_mfa_recovery_reason_chk
    CHECK (length(btrim(reason)) BETWEEN 10 AND 500),
  CONSTRAINT platform_mfa_recovery_terminal_reason_chk
    CHECK (terminal_reason IS NULL OR length(terminal_reason) <= 120),
  -- The initiator's request is the first approval.
  CONSTRAINT platform_mfa_recovery_first_approval_chk
    CHECK (approved_by = requested_by AND approved_session_id = requested_session_id),
  CONSTRAINT platform_mfa_recovery_requester_not_target_chk
    CHECK (requested_by <> target_user_id AND approved_by <> target_user_id),
  CONSTRAINT platform_mfa_recovery_second_approval_chk
    CHECK (
      (second_approved_by IS NULL AND second_session_id IS NULL AND second_approved_at IS NULL)
      OR (second_approved_by IS NOT NULL AND second_session_id IS NOT NULL AND second_approved_at IS NOT NULL
          AND second_approved_by <> target_user_id
          AND second_approved_by <> approved_by
          AND second_approved_by <> requested_by
          AND second_session_id <> approved_session_id)
    ),
  CONSTRAINT platform_mfa_recovery_executor_chk
    CHECK (executed_by IS NULL OR (executed_by <> target_user_id AND executed_session_id IS NOT NULL)),
  CONSTRAINT platform_mfa_recovery_cooling_off_floor_chk
    CHECK (target_kind = 'super_admin' OR cooling_off_until >= created_at + interval '15 minutes'),
  CONSTRAINT platform_mfa_recovery_grant_hash_chk
    CHECK (grant_hash IS NULL OR grant_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT platform_mfa_recovery_grant_fields_chk
    CHECK ((grant_hash IS NULL) = (grant_issued_at IS NULL) AND (grant_hash IS NULL) = (grant_expires_at IS NULL)),
  CONSTRAINT platform_mfa_recovery_grant_expiry_chk
    CHECK (grant_expires_at IS NULL OR grant_expires_at <= grant_issued_at + interval '30 minutes'),
  CONSTRAINT platform_mfa_recovery_redeemed_pair_chk
    CHECK ((grant_redeemed_at IS NULL) = (redeemed_session_id IS NULL)),
  CONSTRAINT platform_mfa_recovery_grant_attempts_chk
    CHECK (grant_failed_attempts >= 0),
  CONSTRAINT platform_mfa_recovery_execution_fields_chk
    CHECK (
      (status IN ('requested', 'approved', 'cancelled', 'denied') AND executed_at IS NULL AND grant_hash IS NULL)
      OR (status IN ('executed_awaiting_enrolment', 'completed', 'failed')
          AND executed_at IS NOT NULL AND executed_by IS NOT NULL AND grant_hash IS NOT NULL)
      OR status = 'expired'
    ),
  CONSTRAINT platform_mfa_recovery_enrolment_window_chk
    CHECK (executed_at IS NULL OR expires_at <= executed_at + interval '24 hours'),
  CONSTRAINT platform_mfa_recovery_completed_chk
    CHECK (status <> 'completed'
           OR (completed_at IS NOT NULL AND replacement_factor_id IS NOT NULL AND grant_redeemed_at IS NOT NULL)),
  CONSTRAINT platform_mfa_recovery_cancelled_chk
    CHECK (status <> 'cancelled' OR (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL)),
  -- Dormant identity-verification extension point (no provider, no documents, no biometrics).
  CONSTRAINT platform_mfa_recovery_evidence_chk
    CHECK ((evidence_type IS NULL AND evidence_ref IS NULL)
           OR (evidence_type = 'identity_verification' AND length(evidence_ref) BETWEEN 1 AND 200))
);

CREATE UNIQUE INDEX platform_mfa_recovery_requests_one_active_per_target
  ON public.platform_mfa_recovery_requests (target_user_id)
  WHERE status IN ('requested', 'approved', 'executed_awaiting_enrolment');

CREATE INDEX platform_mfa_recovery_requests_created_idx
  ON public.platform_mfa_recovery_requests (created_at DESC);

COMMENT ON TABLE public.platform_mfa_recovery_requests IS
  'G7F-3C3 privileged MFA recovery requests (Option D). Mutated only by service_role recovery RPCs. grant_hash is a SHA-256 digest of the one-time grant and is not readable by any client role.';

-- ---------------------------------------------------------------------------------------------
-- 3. Recovery locks: a row here suspends all platform authority for user_id
-- ---------------------------------------------------------------------------------------------
CREATE TABLE public.platform_mfa_recovery_locks (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  request_id uuid NOT NULL REFERENCES public.platform_mfa_recovery_requests(id) ON DELETE CASCADE,
  locked_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.platform_mfa_recovery_locks IS
  'G7F-3C3: users whose MFA factor was removed by recovery. is_super_owner/is_super_admin return false while a row exists. Removed only by complete_platform_mfa_recovery; expiry never removes it.';

-- ---------------------------------------------------------------------------------------------
-- 4. Client access: RLS on, no policies, no client grants; service_role read-only minus grant_hash
-- ---------------------------------------------------------------------------------------------
ALTER TABLE public.platform_mfa_recovery_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.platform_mfa_recovery_locks ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.platform_mfa_recovery_requests FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON TABLE public.platform_mfa_recovery_locks FROM PUBLIC, anon, authenticated, service_role;

GRANT SELECT (
  id, target_user_id, target_kind, target_factor_id,
  requested_by, approved_by, approved_at, second_approved_by, second_approved_at,
  executed_by, cancelled_by, reason, terminal_reason, cooling_off_until, status,
  created_at, executed_at, completed_at, cancelled_at, expires_at,
  grant_issued_at, grant_expires_at, grant_redeemed_at, replacement_factor_id,
  evidence_type, updated_at
) ON public.platform_mfa_recovery_requests TO service_role;
GRANT SELECT ON public.platform_mfa_recovery_locks TO service_role;

-- ---------------------------------------------------------------------------------------------
-- 5. Write guard + lifecycle trigger
-- ---------------------------------------------------------------------------------------------
CREATE FUNCTION public.g7f3c3_guard_recovery_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user uuid;
BEGIN
  IF pg_catalog.current_setting('g7f3c3.rpc', true) = 'on' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF TG_TABLE_NAME = 'platform_mfa_recovery_locks' THEN
      v_user := OLD.user_id;
    ELSE
      v_user := OLD.target_user_id;
    END IF;
    -- Cascade from auth.users deletion only.
    IF NOT EXISTS (SELECT 1 FROM auth.users u WHERE u.id = v_user) THEN
      RETURN OLD;
    END IF;
  END IF;
  RAISE EXCEPTION 'mfa_recovery_state_rpc_only' USING ERRCODE = 'insufficient_privilege';
END;
$$;

CREATE FUNCTION public.g7f3c3_validate_recovery_transition()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'requested' OR NEW.executed_at IS NOT NULL OR NEW.grant_hash IS NOT NULL
       OR NEW.second_approved_by IS NOT NULL OR NEW.completed_at IS NOT NULL OR NEW.cancelled_at IS NOT NULL
       OR NEW.grant_redeemed_at IS NOT NULL OR NEW.replacement_factor_id IS NOT NULL THEN
      RAISE EXCEPTION 'mfa_recovery_invalid_initial_state' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  IF OLD.status IN ('completed', 'cancelled', 'expired', 'denied', 'failed') THEN
    RAISE EXCEPTION 'mfa_recovery_terminal_state' USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.target_user_id IS DISTINCT FROM OLD.target_user_id
     OR NEW.target_kind IS DISTINCT FROM OLD.target_kind
     OR NEW.target_factor_id IS DISTINCT FROM OLD.target_factor_id
     OR NEW.requested_by IS DISTINCT FROM OLD.requested_by
     OR NEW.requested_session_id IS DISTINCT FROM OLD.requested_session_id
     OR NEW.approved_by IS DISTINCT FROM OLD.approved_by
     OR NEW.approved_session_id IS DISTINCT FROM OLD.approved_session_id
     OR NEW.approved_at IS DISTINCT FROM OLD.approved_at
     OR NEW.reason IS DISTINCT FROM OLD.reason
     OR NEW.created_at IS DISTINCT FROM OLD.created_at
     OR NEW.cooling_off_until IS DISTINCT FROM OLD.cooling_off_until
     OR NEW.evidence_type IS DISTINCT FROM OLD.evidence_type
     OR NEW.evidence_ref IS DISTINCT FROM OLD.evidence_ref THEN
    RAISE EXCEPTION 'mfa_recovery_immutable_field' USING ERRCODE = 'check_violation';
  END IF;

  IF OLD.second_approved_by IS NOT NULL AND (
       NEW.second_approved_by IS DISTINCT FROM OLD.second_approved_by
       OR NEW.second_session_id IS DISTINCT FROM OLD.second_session_id
       OR NEW.second_approved_at IS DISTINCT FROM OLD.second_approved_at) THEN
    RAISE EXCEPTION 'mfa_recovery_immutable_field' USING ERRCODE = 'check_violation';
  END IF;

  IF OLD.executed_at IS NOT NULL AND (
       NEW.executed_at IS DISTINCT FROM OLD.executed_at
       OR NEW.executed_by IS DISTINCT FROM OLD.executed_by
       OR NEW.executed_session_id IS DISTINCT FROM OLD.executed_session_id) THEN
    RAISE EXCEPTION 'mfa_recovery_immutable_field' USING ERRCODE = 'check_violation';
  END IF;

  IF NOT (
       (OLD.status = 'requested' AND NEW.status IN ('approved', 'executed_awaiting_enrolment', 'cancelled', 'expired', 'denied'))
    OR (OLD.status = 'approved' AND NEW.status IN ('executed_awaiting_enrolment', 'cancelled', 'expired', 'denied'))
    OR (OLD.status = 'executed_awaiting_enrolment' AND NEW.status IN ('executed_awaiting_enrolment', 'completed', 'expired', 'failed'))
  ) THEN
    RAISE EXCEPTION 'mfa_recovery_invalid_transition' USING ERRCODE = 'check_violation';
  END IF;

  NEW.updated_at := pg_catalog.now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER platform_mfa_recovery_requests_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.platform_mfa_recovery_requests
  FOR EACH ROW EXECUTE FUNCTION public.g7f3c3_guard_recovery_write();

CREATE TRIGGER platform_mfa_recovery_requests_lifecycle
  BEFORE INSERT OR UPDATE ON public.platform_mfa_recovery_requests
  FOR EACH ROW EXECUTE FUNCTION public.g7f3c3_validate_recovery_transition();

CREATE TRIGGER platform_mfa_recovery_locks_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.platform_mfa_recovery_locks
  FOR EACH ROW EXECUTE FUNCTION public.g7f3c3_guard_recovery_write();

